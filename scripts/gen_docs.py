#!/usr/bin/env python3
"""Regenerate docs/rules/<ID>.md and the rule table in docs/rules/README.md from rule docstrings.

Usage: python scripts/gen_docs.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

from toollint.docs import render_rule_markdown
from toollint.rules import all_rules

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs" / "rules"


def rule_table() -> str:
    lines = ["| Code | Name | Category | Severity | Autofix | Summary |", "|---|---|---|---|---|---|"]
    for r in all_rules():
        lines.append(
            f"| [`{r.id}`]({r.id}.md) | `{r.name}` | {r.category.value} | {r.severity.value} | {'yes' if r.fixable else ''} | {r.summary} |"
        )
    return "\n".join(lines) + "\n"


def expected() -> dict[Path, str]:
    out = {DOCS / f"{r.id}.md": render_rule_markdown(r) for r in all_rules()}
    out[DOCS / "README.md"] = (
        "# Rules\n\n"
        "Generated by `scripts/gen_docs.py` from the rule docstrings. Do not edit by hand.\n\n" + rule_table()
    )
    return out


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, content in expected().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if check and stale:
        print("Rule docs are out of date; run: python scripts/gen_docs.py", file=sys.stderr)
        for p in stale:
            print(f"  {p.relative_to(ROOT)}", file=sys.stderr)
        return 1
    if not check:
        print(f"Wrote {len(stale)} file(s)" if stale else "Docs up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
